const DW_LOCALES = ['en', 'ru', 'uk', 'es', 'pt', 'de'];
const DW_LANG_NAMES = {
  en: '🌐 English',
  ru: '🌐 Русский',
  uk: '🌐 Українська',
  es: '🌐 Español',
  pt: '🌐 Português',
  de: '🌐 Deutsch',
};

function dwDetectLang() {
  const saved = localStorage.getItem('dw_lang');
  if (saved && DW_LOCALES.includes(saved)) return saved;
  const list = navigator.languages && navigator.languages.length
    ? [...navigator.languages]
    : [navigator.language || 'en'];
  for (const raw of list) {
    const code = String(raw || '').toLowerCase().split('-')[0];
    if (DW_LOCALES.includes(code)) return code;
  }
  return 'en';
}

function dwApply(lang) {
  const t = DW_T[lang] || DW_T.en;
  if (!t) return;
  const resolved = DW_T[lang] ? lang : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t[el.dataset.i18n]; if (v !== undefined) el.innerHTML = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = t[el.dataset.i18nPh]; if (v !== undefined) el.placeholder = v;
  });
  const label = document.getElementById('dwLangLabel');
  if (label) label.textContent = DW_LANG_NAMES[resolved] || ('🌐 ' + resolved.toUpperCase());
  const codeEl = document.getElementById('dwNavLangCode');
  if (codeEl) codeEl.textContent = resolved.toUpperCase();
  const navSelect = document.getElementById('dwNavLangSelect');
  if (navSelect) navSelect.value = resolved;
  document.querySelectorAll('.lang-menu-item, .nav-lang-item').forEach(b =>
    b.classList.toggle('lang-active', b.dataset.lang === resolved)
  );
  document.documentElement.lang = resolved;
  localStorage.setItem('dw_lang', resolved);
  if (typeof dwFitCreatorCard === 'function') dwFitCreatorCard();
  if (typeof dwFitChordDemo === 'function') dwFitChordDemo();
}

function dwSwitch(lang) {
  dwApply(lang);
  const btn  = document.getElementById('dwLangBtn');
  const menu = document.getElementById('dwLangMenu');
  if (btn)  btn.classList.remove('open');
  if (menu) menu.classList.remove('open');
  const nbtn  = document.getElementById('dwNavLangBtn');
  const nmenu = document.getElementById('dwNavLangMenu');
  if (nbtn)  nbtn.classList.remove('open');
  if (nmenu) nmenu.classList.remove('open');
}

function dwToggleLang() {
  const btn  = document.getElementById('dwLangBtn');
  const menu = document.getElementById('dwLangMenu');
  if (!btn || !menu) return;
  btn.classList.toggle('open');
  menu.classList.toggle('open');
  // close nav switcher if open
  const nbtn  = document.getElementById('dwNavLangBtn');
  const nmenu = document.getElementById('dwNavLangMenu');
  if (nbtn)  nbtn.classList.remove('open');
  if (nmenu) nmenu.classList.remove('open');
}

function dwToggleNavLang() {
  const btn  = document.getElementById('dwNavLangBtn');
  const menu = document.getElementById('dwNavLangMenu');
  if (!btn || !menu) return;
  btn.classList.toggle('open');
  menu.classList.toggle('open');
  const fbtn  = document.getElementById('dwLangBtn');
  const fmenu = document.getElementById('dwLangMenu');
  if (fbtn)  fbtn.classList.remove('open');
  if (fmenu) fmenu.classList.remove('open');
}

document.addEventListener('click', e => {
  if (!e.target.closest('.lang-drop')) {
    const btn  = document.getElementById('dwLangBtn');
    const menu = document.getElementById('dwLangMenu');
    if (btn)  btn.classList.remove('open');
    if (menu) menu.classList.remove('open');
  }
  if (!e.target.closest('.nav-lang')) {
    const btn  = document.getElementById('dwNavLangBtn');
    const menu = document.getElementById('dwNavLangMenu');
    if (btn)  btn.classList.remove('open');
    if (menu) menu.classList.remove('open');
  }
  if (!e.target.closest('nav')) {
    const ham      = document.querySelector('.hamburger');
    const navLinks = document.querySelector('.nav-links');
    if (ham)      ham.classList.remove('open');
    if (navLinks) navLinks.classList.remove('open');
  }
});

document.addEventListener('DOMContentLoaded', () => {
  dwApply(dwDetectLang());

  const navSelect = document.getElementById('dwNavLangSelect');
  if (navSelect) {
    navSelect.addEventListener('change', () => dwSwitch(navSelect.value));
  }

  const ham      = document.querySelector('.hamburger');
  const navLinks = document.querySelector('.nav-links');
  if (ham && navLinks) {
    ham.addEventListener('click', e => {
      e.stopPropagation();
      ham.classList.toggle('open');
      navLinks.classList.toggle('open');
    });
    navLinks.querySelectorAll('a').forEach(a =>
      a.addEventListener('click', () => {
        ham.classList.remove('open');
        navLinks.classList.remove('open');
      })
    );
  }
});
